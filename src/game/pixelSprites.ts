const spriteCache = new Map<string, HTMLCanvasElement>();

export function getSpriteCanvas(spriteId: string): HTMLCanvasElement {
  const cached = spriteCache.get(spriteId);
  if (cached) return cached;

  const matrix = SPRITES[spriteId] ?? SPRITES.item_charm_gold;
  const height = matrix.length;
  const width = matrix[0]?.length ?? 16;

  const canvas = document.createElement('canvas');
  canvas.width = width;
  canvas.height = height;
  const ctx = canvas.getContext('2d');
  if (ctx) {
    for (let y = 0; y < height; y++) {
      const row = matrix[y];
      for (let x = 0; x < width; x++) {
        const ch = row[x];
        const color = PAL[ch];
        if (color) {
          ctx.fillStyle = color;
          ctx.fillRect(x, y, 1, 1);
        }
      }
    }
  }
  spriteCache.set(spriteId, canvas);
  return canvas;
}

const auraCache = new Map<string, HTMLCanvasElement>();

export function getSpriteAuraCanvas(spriteId: string, color: string): HTMLCanvasElement {
  const key = `${spriteId}::${color}`;
  const cached = auraCache.get(key);
  if (cached) return cached;

  const matrix = SPRITES[spriteId] ?? SPRITES.boss_king_slime;
  const height = matrix.length;
  const width = matrix[0]?.length ?? 16;

  const canvas = document.createElement('canvas');
  canvas.width = width + 2;
  canvas.height = height + 2;
  const ctx = canvas.getContext('2d');
  if (ctx) {
    const isSolid = (sx: number, sy: number) => {
      if (sx < 0 || sy < 0 || sx >= width || sy >= height) return false;
      const ch = matrix[sy]?.[sx] ?? '.';
      return ch !== '.' && Boolean(PAL[ch]);
    };

    ctx.fillStyle = color;
    for (let ay = 0; ay < height + 2; ay++) {
      for (let ax = 0; ax < width + 2; ax++) {
        const sx = ax - 1;
        const sy = ay - 1;
        if (isSolid(sx, sy)) continue;
        let touches = false;
        for (let dy = -1; dy <= 1 && !touches; dy++) {
          for (let dx = -1; dx <= 1; dx++) {
            if (dx === 0 && dy === 0) continue;
            if (isSolid(sx + dx, sy + dy)) {
              touches = true;
              break;
            }
          }
        }
        if (touches) {
          ctx.fillRect(ax, ay, 1, 1);
        }
      }
    }
  }
  auraCache.set(key, canvas);
  return canvas;
}

